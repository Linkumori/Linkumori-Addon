// The bundle is not minified, so it can be read and reviewed as is.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const here = path => new URL(path, import.meta.url).pathname;
const pkg = name => JSON.parse(readFileSync(new URL(`./node_modules/${name}/package.json`, import.meta.url)));
const ghostery = pkg('@ghostery/adblocker').version;

const common = {
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'firefox115',
    minify: false,
    legalComments: 'inline',
    charset: 'utf8'
};

