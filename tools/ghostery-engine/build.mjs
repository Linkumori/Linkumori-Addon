// Keep tldts out of the Ghostery bundle: any import of it fails the build.
const noTldts = {
    name: 'no-tldts',
    setup(b) {
        b.onResolve({ filter: /tldts/ }, args => {
            if (args.importer.endsWith('tldts-global.mjs') || args.path.endsWith('tldts-global.mjs')) return undefined;
            if (args.path === 'tldts-experimental') return { path: here('./tldts-global.mjs') };
            return { errors: [{ text: `tldts (MIT) must not be bundled into the Ghostery engine: ${args.path}` }] };
        });
    }
};

await build({
    ...common,
    entryPoints: [here('./entry.mjs')],
    globalName: 'LinkumoriGhosteryEngine',
    banner: { js: ghosteryBanner },
    plugins: [noTldts],
    outfile: here('../../external_js/linkumori-ghostery-engine.js')
});

await build({
    ...common,
    entryPoints: [here('./tldts-entry.mjs')],
    globalName: 'LinkumoriTldts',
    banner: { js: tldtsBanner },
    outfile: here('../../external_js/linkumori-tldts.js')
});

