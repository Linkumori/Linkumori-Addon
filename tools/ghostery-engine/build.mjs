// Replace tldts with the add-on's Public Suffix List: Ghostery's import of
// 'tldts-experimental' resolves to psl-global.mjs, and any other tldts
// import fails the build.
const noTldts = {
    name: 'no-tldts',
    setup(b) {
        b.onResolve({ filter: /tldts/ }, args => {
            if (args.path === 'tldts-experimental') return { path: here('./psl-global.mjs') };
            return { errors: [{ text: `tldts must not be bundled into the Ghostery engine: ${args.path}` }] };
        });
    }
};

await build({
    ...common,
    entryPoints: [here('./entry.mjs')],
    globalName: 'LinkumoriGhosteryEngine',
    banner: { js: ghosteryBanner },
    plugins: [noTldts],
    outfile: here('../../external_js/linkumori-ghostery-engine.js')
});

console.log(`external_js/linkumori-ghostery-engine.js: @ghostery/adblocker ${ghostery}`);
